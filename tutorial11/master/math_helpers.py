def add(a, b):
    """
    (number, number) -> number
    Returns the sum of a and b.
    """
    return a + b


def multiply(a, b):
    """
    (number, number) -> number
    Returns the product of a and b.
    """
    return a * b


def average(numbers):
    """
    (list of number) -> float
    Returns the average of a list of numbers.
    """
    return sum(numbers) / len(numbers)
